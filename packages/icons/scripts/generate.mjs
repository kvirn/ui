import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), '..')

const rootAttributes = {
  viewBox: '0 0 24 24',
  fill: 'none',
  stroke: 'currentColor',
  'stroke-width': '1.5',
  'stroke-linecap': 'round',
  'stroke-linejoin': 'round',
}
const allowedShapes = {
  path: ['d', 'pathLength', 'stroke-dasharray'],
  line: ['x1', 'y1', 'x2', 'y2'],
  polyline: ['points'],
  circle: ['cx', 'cy', 'r'],
  ellipse: ['cx', 'cy', 'rx', 'ry'],
  rect: ['x', 'y', 'width', 'height', 'rx', 'ry'],
}
const reactProperties = { 'stroke-dasharray': 'strokeDasharray' }
const reservedWords = new Set(['delete', 'new', 'default', 'import', 'export', 'switch', 'return'])
const kebabName = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/

const header = '// Generated by scripts/generate.mjs from svg/*.svg. Do not edit.\n'

class IconSourceError extends Error {
  constructor(file, reason) {
    super(`${file}: ${reason}`)
  }
}

function readAttributes(file, text) {
  const attributes = {}
  const unread = text.replace(/([\w:-]+)\s*=\s*"([^"]*)"/g, (_, name, value) => {
    attributes[name] = value
    return ''
  })
  if (unread.trim()) {
    throw new IconSourceError(file, `attributes must be written name="value", got ${unread.trim()}`)
  }
  return attributes
}

export function parseIcon(file, source) {
  const root = source.match(/^\s*(?:<\?xml[^>]*\?>\s*)?<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/)
  if (!root) throw new IconSourceError(file, 'expected one <svg> root element')
  const { xmlns, ...attributes } = readAttributes(file, root[1])
  if (xmlns !== undefined && xmlns !== 'http://www.w3.org/2000/svg') {
    throw new IconSourceError(file, `unexpected xmlns "${xmlns}"`)
  }
  for (const [name, expected] of Object.entries(rootAttributes)) {
    if (attributes[name] !== expected) {
      throw new IconSourceError(
        file,
        `root ${name} must be "${expected}", got "${attributes[name]}"`,
      )
    }
  }
  for (const name of Object.keys(attributes)) {
    if (!(name in rootAttributes))
      throw new IconSourceError(file, `root attribute ${name} is not allowed`)
  }
  const shapes = []
  const body = root[2].replace(/<!--[\s\S]*?-->/g, '')
  const elements = body.match(/<[^>]+>/g) ?? []
  const residue = body.replace(/<[^>]+>/g, '').trim()
  if (residue) throw new IconSourceError(file, `unexpected text "${residue}"`)
  for (const element of elements) {
    const tag = element.match(/^<\s*([\w:-]+)/)?.[1]
    if (!tag || element.startsWith('</'))
      throw new IconSourceError(file, `unexpected markup ${element}`)
    if (!(tag in allowedShapes)) throw new IconSourceError(file, `<${tag}> is not allowed`)
    const shapeAttributes = readAttributes(
      file,
      element.replace(/^<\s*[\w:-]+/, '').replace(/\/?>$/, ''),
    )
    for (const name of Object.keys(shapeAttributes)) {
      if (!allowedShapes[tag].includes(name)) {
        throw new IconSourceError(file, `<${tag}> attribute ${name} is not allowed`)
      }
    }
    if (Object.keys(shapeAttributes).length === 0)
      throw new IconSourceError(file, `<${tag}> has no attributes`)
    shapes.push([tag, shapeAttributes])
  }
  if (shapes.length === 0) throw new IconSourceError(file, 'no shapes')
  return shapes
}

export function camelCase(name) {
  const camel = name.replace(/-([a-z0-9])/g, (_, character) => character.toUpperCase())
  return reservedWords.has(camel) ? `${camel}Icon` : camel
}

const quote = (text) => `'${text.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`

// The text matches what `vp fmt` prints (100 columns), so formatting generated files changes nothing.
const printWidth = 100

function shapeText([tag, attributes], indent) {
  const entries = Object.entries(attributes).map(
    ([key, value]) => `${reactProperties[key] ?? key}: ${quote(value)}`,
  )
  const inline = `[${quote(tag)}, { ${entries.join(', ')} }]`
  if (indent.length + inline.length + 1 <= printWidth) return inline
  const object = `${indent}  { ${entries.join(', ')} },`
  const objectText =
    object.length <= printWidth
      ? object
      : `${indent}  {\n${entries.map((entry) => `${indent}    ${entry},`).join('\n')}\n${indent}  },`
  return `[\n${indent}  ${quote(tag)},\n${objectText}\n${indent}]`
}

function callText(shapes, indent, prefix, suffix) {
  const inline = `${indent}${prefix}createIcon([${shapes.map((shape) => shapeText(shape, indent)).join(', ')}])${suffix}`
  if (shapes.length === 1 && inline.length <= printWidth) return inline
  const lines = shapes.map((shape) => `${indent}  ${shapeText(shape, `${indent}  `)},`).join('\n')
  return `${indent}${prefix}createIcon([\n${lines}\n${indent}])${suffix}`
}

function moduleText(name, shapes, mirrored) {
  const declaration = `export const ${camelCase(name)}: IconRegistryEntry = `
  const body = mirrored
    ? `${declaration}{\n${callText(shapes, '  ', 'component: ', ',')}\n  mirrorInRtl: true,\n}`
    : callText(shapes, '', declaration, '')
  return `${header}import { createIcon } from '../create-icon.ts'
import type { IconRegistryEntry } from '@kvirn-ui/react'

${body}
`
}

/** Every generated file as a map from its path under the package to its text. */
export function buildOutputs(svgDirectory, mirrorInRtl) {
  const names = readdirSync(svgDirectory)
    .filter((file) => file.endsWith('.svg'))
    .map((file) => file.slice(0, -'.svg'.length))
    .sort()
  const outputs = new Map()
  for (const name of names) {
    if (!kebabName.test(name))
      throw new IconSourceError(`${name}.svg`, 'name must be lower-case kebab-case')
  }
  for (const name of mirrorInRtl) {
    if (!names.includes(name))
      throw new IconSourceError('mirror-in-rtl.json', `"${name}" has no svg file`)
  }
  for (const name of names) {
    const shapes = parseIcon(`${name}.svg`, readFileSync(join(svgDirectory, `${name}.svg`), 'utf8'))
    outputs.set(`src/icons/${name}.ts`, moduleText(name, shapes, mirrorInRtl.includes(name)))
  }
  outputs.set(
    'src/index.ts',
    `${header}${names.map((name) => `export { ${camelCase(name)} } from './icons/${name}.ts'`).join('\n')}\n`,
  )
  outputs.set(
    'src/all.ts',
    `${header}${names.map((name) => `import { ${camelCase(name)} } from './icons/${name}.ts'`).join('\n')}

/** Every icon in the library, keyed by its kebab-case name. Pass it to \`KvirnProvider icons\`. */
export const allIcons = {
${names.map((name) => `  ${/^[a-z][a-z0-9]*$/.test(name) ? name : quote(name)}: ${camelCase(name)},`).join('\n')}
} as const

export const iconNames = [
${names.map((name) => `  ${quote(name)},`).join('\n')}
] as const

export type LibraryIconName = (typeof iconNames)[number]
`,
  )
  return outputs
}

export function readMirrorList() {
  return JSON.parse(readFileSync(join(packageRoot, 'mirror-in-rtl.json'), 'utf8'))
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const outputs = buildOutputs(join(packageRoot, 'svg'), readMirrorList())
  const iconsDirectory = join(packageRoot, 'src/icons')
  rmSync(iconsDirectory, { recursive: true, force: true })
  mkdirSync(iconsDirectory, { recursive: true })
  for (const [path, text] of outputs) writeFileSync(join(packageRoot, path), text)
  console.log(`Generated ${outputs.size - 2} icons.`)
}
